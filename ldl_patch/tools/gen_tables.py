"""Generate src/zscript/rsldp/tables.zs from what was parsed and measured (never typed by hand):
  parsed/ld_replaces.txt       LegenDoom 3.0's `replaces` (parse_ld.py, from the pk3)
  parsed/repl_full_hard.txt    each replacee's final class on the rig WITHOUT LegenDoom, full order with XMVE,
                               skill Hard (the one BD22 skill with no ReplaceActor), probe `rsldpp_repl`
  parsed/repl_bdonly_hard.txt  the same without XMVE (brutal22test6 -> voxels -> BD22 VR only)
  parsed/ld_rolls.txt          which effects each LegenDoom weapon slot can roll, per rarity (parse_ld.py)
and the list of effects the patch carries onto BD22 VR weapons (IMPLEMENTED below, matching effects.zs).
Prints coverage: per slot and rarity, how many rollable effects the bridge carries.
Usage: python3 -I gen_tables.py   (run from ldl_patch/tools)
"""
import os, collections
here = os.path.dirname(os.path.abspath(__file__))
P = lambda f: os.path.join(here, 'parsed', f)
out = os.path.join(here, '..', 'src', 'zscript', 'rsldp', 'tables.zs')

# effects.zs implements exactly these (keep in sync; build.py checks every name appears in effects.zs)
IMPLEMENTED = [
    # kill: LegenDoom's own <Effect>EffectDeath item, given to the dead monster with the player as its target
    'Artifact', 'Battlerage', 'Bloodthirsty', 'Bloody', 'Divine', 'Endless', 'Hopeful', 'Infiltrator',
    'Killstreaker', 'Murderous', 'Unstoppable', 'WarmUp',
    # hit, monster side: LegenDoom's own debuff items, given to the hit monster as its puffs do
    'Crippling', 'Whittling', 'Freezing', 'Gravitic', 'Incinerating', 'Violent', 'Persistent', 'Igniting',
    # hit, player side
    'Vampiric', 'Scavenging', 'Sadistic', 'Painful', 'Thieving',
    # damage multipliers (player state)
    'Pristine', 'Raging', 'Rampaging', 'Serious', 'ProStrat', 'SteadyShot', 'Machine', 'CQC', 'Patient',
    'Lucky', 'Berserker', 'AntiTree', 'Annoying',
    # damage multipliers (target)
    'Exorcist', 'Extinguishing', 'Wrangler', 'Antiair', 'Scrapper', 'Blessed', 'Heroic', 'DemonSlayer',
    # ammo
    'Unlikely', 'Improbable', 'Efficient', 'Impossible',
    # while held, not firing / firing
    'Replicating', 'Regenerating', 'Determined', 'Sensing', 'Desperate',
    # map start (LegenDoom's own ACS gives the vanilla ammo; the patch fills BD22's)
    'Resupplying',
]

def table(f):
    d = collections.OrderedDict()
    for line in open(P(f)):
        p = line.split()
        if len(p) >= 3 and p[0] == 'REPL':
            d[p[1]] = p[2]
    return d

ldrep = [l.split() for l in open(P('ld_replaces.txt'))]
full, bdo, withld = table('repl_full_hard.txt'), table('repl_bdonly_hard.txt'), table('repl_with_ld_nopatch.txt')
rows = []
for replacee, ldcls, _src in ldrep:
    a = full.get(replacee, replacee); b = bdo.get(replacee, replacee)
    rows.append((replacee, ldcls, a, b))
    pass  # with LegenDoom (nopatch run, skill normal) every replacee resolves to the LD class except where a skill ReplaceActor wins

rolls = [l.split() for l in open(P('ld_rolls.txt'))]
impl = set(IMPLEMENTED)
cov = collections.defaultdict(lambda: [0, 0])
for s, r, e in rolls:
    cov[(s, r)][1] += 1
    if e in impl:
        cov[(s, r)][0] += 1

z = ['// GENERATED by tools/gen_tables.py from tools/parsed/* -- do not edit by hand.', '',
     'class RSLDP_Tables', '{',
     '\t// LegenDoom 3.0 replacee | LegenDoom class | final class without LegenDoom (full order, XMVE) | same, BD22 VR only',
     '\tstatic const string Repl[] =', '\t{']
z += [',\n'.join('\t\t"%s|%s|%s|%s"' % r for r in rows)]
z += ['\t};', '',
      '\t// effects the bridge carries onto BD22 VR weapons', '\tstatic const string Implemented[] =', '\t{']
z += [',\n'.join('\t\t"%s"' % e for e in IMPLEMENTED)]
z += ['\t};', '', '\t// slot|rarity|effect: what LegenDoom 3.0 can roll (for re-rolling an effect the bridge does not carry)',
      '\tstatic const string Rolls[] =', '\t{']
z += [',\n'.join('\t\t"%s|%s|%s"' % tuple(r) for r in rolls)]
z += ['\t};', '}', '']
os.makedirs(os.path.dirname(out), exist_ok=True)
open(out, 'w').write('\n'.join(z))
print('wrote', os.path.normpath(out), ': %d replacements, %d implemented effects, %d rolls' % (len(rows), len(IMPLEMENTED), len(rolls)))
tot_i = tot = 0
for (s, r), (i, n) in sorted(cov.items()):
    tot_i += i; tot += n
    print('  %-15s %-9s carried %2d of %2d' % (s, r, i, n))
print('  all slots: carried %d of %d rollable (slot, effect) pairs' % (tot_i, tot))
for e in IMPLEMENTED:
    if not any(x[2] == e for x in rolls):
        print('  WARNING: implemented effect never rolls:', e)

# LD mode inside BD22 VR (merge, 2026-11-06): the same measured tables for src/zscript/rsld/tables.zs (class
# RSLD_Tables). Which effects are carried is no longer a list here: it is every RSLD_Fx_<Name> class (the registry).
out2 = os.path.join(here, '..', '..', 'src', 'zscript', 'rsld', 'tables.zs')
z2 = ['// GENERATED by ldl_patch/tools/gen_tables.py from ldl_patch/tools/parsed/* -- do not edit by hand.', '',
      'class RSLD_Tables', '{',
      '\t// LegenDoom 3.0 replacee | LegenDoom class | final class without LegenDoom (full order, XMVE) | same, BD22 VR only',
      '\tstatic const string Repl[] =', '\t{']
z2 += [',\n'.join('\t\t"%s|%s|%s|%s"' % r for r in rows)]
z2 += ['\t};', '', '\t// slot|rarity|effect: what LegenDoom 3.0 can roll (parse_ld.py, LD<Slot>RandomLegendary)',
       '\tstatic const string Rolls[] =', '\t{']
z2 += [',\n'.join('\t\t"%s|%s|%s"' % tuple(r) for r in rolls)]
z2 += ['\t};', '}', '']
open(out2, 'w').write('\n'.join(z2))
print('wrote', os.path.normpath(out2))
