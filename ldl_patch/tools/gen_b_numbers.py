"""Agent B (G1, G8, G10): run Agent A's number generator (gen_ld_numbers.py) on B's rules files only.

  python3 -I ldl_patch/tools/gen_b_numbers.py            writes src/zscript/rsld/numbers_g1.zs, numbers_g8.zs, numbers_g10.zs
  python3 -I ldl_patch/tools/gen_b_numbers.py --check    resolves every rule and prints value + source line, writes nothing

Same rule syntax and same output as gen_ld_numbers.py (its own resolve() is used), so a full run of
gen_ld_numbers.py writes byte-identical tables. This only exists so B's tables can be (re)made while another
group's rules file does not resolve yet.
"""
import os, re, sys, shlex

HERE = os.path.dirname(os.path.abspath(__file__))
GROUPS = ['g1', 'g8', 'g10']

src = open(os.path.join(HERE, 'gen_ld_numbers.py')).read()
src = re.sub(r'\nmain\(\)\s*$', '\n', src)	# load the generator's functions without running its main()
g = {'__file__': os.path.join(HERE, 'gen_ld_numbers.py'), '__name__': 'gen_ld_numbers'}
exec(compile(src, 'gen_ld_numbers.py', 'exec'), g)

check = '--check' in sys.argv
for group in GROUPS:
    fn = group + '.rules'
    rows = []
    for ln, raw in enumerate(open(os.path.join(HERE, 'numbers', fn)), 1):
        raw = re.split(r'\s#\s', raw)[0]
        t = raw.strip()
        if not t or t.startswith('#'):
            continue
        rule = shlex.split(t, comments=False)
        try:
            v, line, s = g['resolve'](rule)
        except Exception as e:
            raise SystemExit('%s:%d: %s (%s)' % (fn, ln, e, t))
        s = s.replace('\\', '\\\\').replace('"', "'").replace('\t', ' ')
        rows.append('%s|%s|%s|%s:%d|%s' % (rule[0], rule[1], v, rule[2], line, s))
        if check:
            print('%-14s %-14s %8s  %s:%d  %s' % (rule[0], rule[1], v, rule[2], line, s[:90]))
    if check:
        continue
    cls = 'RSLD_Numbers_' + re.sub(r'\W', '_', group)
    out = ['// GENERATED by ldl_patch/tools/gen_ld_numbers.py from ldl_patch/tools/numbers/%s -- do not edit.' % fn,
           '// LegenDoom 3.0 numbers, each with the file:line it was read from.', '',
           'class %s : RSLD_NumberTable' % cls, '{', '\tstatic const string Rows[] =', '\t{']
    out.append(',\n'.join('\t\t"%s"' % r for r in rows))
    out += ['\t};', '\toverride int Count() { return Rows.Size(); }', '\toverride string Row(int i) { return Rows[i]; }', '}', '']
    p = os.path.join(g['OUTDIR'], 'numbers_%s.zs' % group)
    open(p, 'w').write('\n'.join(out))
    print('%s: %d numbers -> %s' % (fn, len(rows), os.path.relpath(p, g['REPO'])))
