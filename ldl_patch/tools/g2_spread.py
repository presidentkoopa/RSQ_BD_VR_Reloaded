#!/usr/bin/env python3
"""G2 (Agent C): our guns' own pellet volleys, parsed from BD22 VR's DECORATE -> src/zscript/rsld/ld_g2_spread.zs.

LegenDoom's pellet effects (Renegade, TwinShot, TripleThreat, ShortRange, Choked) add or move pellets. On our guns an
added pellet must get OUR spread for the volley it belongs to (the shotgun stays our shotgun). A_FireBullets rolls each
pellet's spread inside (spread_xy, spread_z) (gzdoom stateprovider.zs:194-195): this tool reads those numbers, in
firing order, for each gun's fire sequence, so a pellet's index in its pull names its volley.

  python3 ldl_patch/tools/g2_spread.py      (run from the repo root; writes src/zscript/rsld/ld_g2_spread.zs)

Never typed: every row names its .dec line. The pump's "Pump Shotgun Spread" ternary (rsq_pump_spread == 1 ?) gives
two values per volley; both are kept. A volley behind A_JumpIfInventory("IsNOTTacticalClass", ...) is Tactical only.
"""
import os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
W = os.path.join(ROOT, 'src', 'actors', 'Weapons')
OUT = os.path.join(ROOT, 'src', 'zscript', 'rsld', 'ld_g2_spread.zs')

# (sequence name, weapon class (subclasses match), file, state label, how many A_FireBullets calls make one pull
#  (0 = all until the next label), match: first pellet damage, first pellet range (0 = full), zoomed (-1 any, 0, 1))
SEQS = [
	('pump',       'Shot_Gun',       'Shotgun.dec',        'ResumeFireFrame:',  0, -1),
	('pump_slug',  'Shot_Gun',       'Shotgun.dec',        'RSA_SlugShot:',     0, -1),
	('ssg',        'SSG',            'SSG.dec',            'ResumeFireFrame:',  0, -1),
	('ssg_one',    'SSG',            'SSG.dec',            'ResumeFire2Frame:', 0, -1),
	('pistol',     'BrutalPistol',   'Pistol.dec',         'ResumeFireFrame:',  1, -1),
	('revolver',   'BrutalRevolver', 'BrutalRevolver.dec', 'Fire:',             1, -1),
	('minigun',    'MiniGun',        'Minigun.dec',        'Hold:',             1, -1),
	('rifle',      'Rifle',          'Rifle.dec',          'ResumeFireFrame:',  1, 0),
	('rifle_aim',  'Rifle',          'Rifle.dec',          'Fire2:',            1, 1),
]

NUM = r'-?[\d.]+'
TERN = r'GetCVar\("rsq_pump_spread"\)\s*==\s*1\s*\?\s*(%s)\s*:\s*(%s)' % (NUM, NUM)


def split_args(s):
	out, d, cur = [], 0, ''
	for ch in s:
		if ch == '(':
			d += 1
		elif ch == ')':
			d -= 1
		if ch == ',' and d == 0:
			out.append(cur.strip())
			cur = ''
		else:
			cur += ch
	out.append(cur.strip())
	return out


def val(a):
	"""(normal, enhanced) for a number or the rsq_pump_spread ternary"""
	m = re.fullmatch(TERN, a)
	if m:
		return float(m.group(2)), float(m.group(1))
	return float(a), float(a)


def volleys(fn, label, take):
	lines = open(os.path.join(W, fn), encoding='latin-1').read().split('\n')
	start = next(i for i, l in enumerate(lines) if l.strip().startswith(label))
	rows = []
	for i in range(start + 1, len(lines)):
		l = lines[i].split('//')[0]
		if re.match(r'\s*[A-Za-z_0-9]+:\s*$', l) and not l.strip().startswith(('SpriteVariant',)):
			break
		m = re.search(r'A_FireBullets\s*\(', l, re.I)
		if not m:
			continue
		j, d = m.end(), 1
		while d:
			d += {'(': 1, ')': -1}.get(l[j], 0)
			j += 1
		a = split_args(l[m.end():j - 1])
		h, he = val(a[0])
		v, ve = val(a[1])
		n = int(a[2])
		n = 1 if n <= 0 else n		# -1: one pellet (stateprovider.zs:181)
		dmg = int(a[3])
		rng = float(a[6]) if len(a) > 6 and a[6] else 0.0
		prev = lines[i - 1] + lines[i - 2] if i >= 2 else ''
		tac = 'IsNOTTacticalClass' in prev
		rows.append((n, h, v, he, ve, dmg, rng, tac, i + 1))
		if take and len(rows) == take:
			break
	return rows


def main():
	seq_rows = []
	vol_rows = []
	for name, cls, fn, label, take, zoom in SEQS:
		rows = volleys(fn, label, take)
		if not rows:
			sys.exit('no A_FireBullets after %s in %s' % (label, fn))
		first = rows[0]
		seq_rows.append('\t\tAddSeq("%s", "%s", %d, %g, %d);\t// %s:%d' % (name, cls, first[5], first[6], zoom, fn, first[8]))
		for n, h, v, he, ve, dmg, rng, tac, ln in rows:
			vol_rows.append('\t\tAddVolley("%s", %d, %g, %g, %g, %g, %d, %g, %s);\t// %s:%d' % (
				name, n, h, v, he, ve, dmg, rng, 'true' if tac else 'false', fn, ln))
	src = '''// ld_g2_spread.zs -- GENERATED by ldl_patch/tools/g2_spread.py from src/actors/Weapons/*.dec. Do not edit by hand.
// G2 (Agent C): each gun's own pellet volleys in firing order, so a pellet LegenDoom adds gets OUR spread.
// AddSeq(name, weapon class, first pellet damage, first pellet range (0 full), zoomed -1 any / 0 / 1)
// AddVolley(sequence, pellets, spread_xy, spread_z, enhanced xy, enhanced z (rsq_pump_spread 1), damage, range, Tactical only)

class RSLD_G2_Spread
{
	Array<String> sName, sClass;
	Array<int> sDmg, sZoom;
	Array<double> sRange;
	Array<String> vSeq;
	Array<int> vN, vDmg;
	Array<double> vH, vV, vHe, vVe, vRange;
	Array<bool> vTac;

	void AddSeq(String n, String c, int d, double r, int z) { sName.Push(n); sClass.Push(c); sDmg.Push(d); sRange.Push(r); sZoom.Push(z); }
	void AddVolley(String s, int n, double h, double v, double he, double ve, int d, double r, bool t)
	{ vSeq.Push(s); vN.Push(n); vH.Push(h); vV.Push(v); vHe.Push(he); vVe.Push(ve); vDmg.Push(d); vRange.Push(r); vTac.Push(t); }

	void Fill()
	{
%s
%s
	}
}
''' % ('\n'.join(seq_rows), '\n'.join(vol_rows))
	os.makedirs(os.path.dirname(OUT), exist_ok=True)
	open(OUT, 'w').write(src)
	print('wrote %s: %d sequences, %d volleys' % (OUT, len(seq_rows), len(vol_rows)))
	for r in seq_rows + vol_rows:
		print(r.strip())


if __name__ == '__main__':
	main()
