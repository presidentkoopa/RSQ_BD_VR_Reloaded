"""gen_off_minigun.py (2.0.5e) -> src/DECORATE.rsqdualmg, src/MODELDEF.rsqdualmg

The owner's dual Minigun (2026-11-22: "The BD chaingun can be dual-wielded"): RSQ_Off_Minigun, the off-hand copy of
BD22's Minigun the way every other off-hand copy is made (DECORATE.rsqdual, MODELDEF.rsqoff: the gun itself, renamed, its
own magazine, the gun's own model blocks under the copy's class). Generated from src/actors/Weapons/Minigun.dec, so the
copy fires, spins up and hits exactly as the gun does. What changes, and why:
  - "Spin" (BD22's spin-up token, a player item) is RSQ_SpinOff, so each hand spins up and down on its own;
  - its magazine is MinigunAmmoOff (200, as the main gun's real magazine, counters.zs CAP), its AmmoType2; the reserve
    (RSQ_MinigunAmmo) is shared, its AmmoType1. Each shot takes one from the magazine (A_TakeInventory before
    A_FireBullets, in place of FBF_USEAMMO, which would spend the shared reserve and read as a main-hand shot in
    counters.zs RealTick); its empty checks read the magazine;
  - its Reload tops the magazine up from the pouch (RSQ_OffFillMinigun, counters.zs OffFill) at BD22's belt sounds; the
    hand-reload states (RSR_*) are left out: a gun in the off hand reloads by the gesture or the Reload button;
  - the reload key's token is the main hand's (as in every copy: OverlayID 1000000 never takes it).
The model blocks: MODELDEF.bd.txt's and MODELDEF.rsqdual's Minigun blocks under RSQ_Off_Minigun. Run from the repo root:
python tools/dual_minigun/gen_off_minigun.py"""
import os, re
ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, 'src')
rd = lambda p: open(os.path.join(SRC, p), encoding='latin-1').read()

dec = rd('actors/Weapons/Minigun.dec')
i = dec.index('ACTOR MiniGun : BrutalWeapon')
j = dec.index('ACTOR PuristMinigun')
body = dec[i:j]
st = body.index('\tStates\n\t{')
states = body[st:]
# the hand-reload states and the posefix Reload go: a new Reload below
a = states.index('\t// posefix rsr (1.97)'); b = states.index('\tSpawn:')
assert a < states.index('\tReload:') < b
states = states[:a] + states[b:]
out = []
lines = states.split('\n')
for k, ln in enumerate(lines):
    if 'RSQ_Empty_Minigun' in ln:
        nxt = lines[k + 1] if k + 1 < len(lines) else ''
        if 'A_FireBullets' in nxt:
            out.append('\t\t"####" "#" 0 A_TakeInventory("MinigunAmmoOff", 1)\t// the shot\'s round, from this hand\'s magazine')
        continue			# the main gun's empty-magazine guard: this one clicks dry (HoldEmpty) instead
    if 'A_JumpIfInventory("Reloading", 1, "Reload")' in ln:
        ln = ln.replace('A_JumpIfInventory("Reloading", 1, "Reload")', 'A_JumpIf(OverlayID() != 1000000 && CountInv("Reloading") > 0, "Reload")')
    out.append(ln)
states = '\n'.join(out)
n_spin = len(re.findall(r'"Spin"', states))
states = re.sub(r'"Spin"', '"RSQ_SpinOff"', states)
states = states.replace('FBF_NORANDOM | FBF_USEAMMO', 'FBF_NORANDOM')
states = states.replace('A_JumpIfNoAmmo(2)', 'A_JumpIf(CountInv("MinigunAmmoOff") < 1, 2)')
states = re.sub(r'A_JumpIfNoAmmo\("(\w+)"\)', r'A_JumpIf(CountInv("MinigunAmmoOff") < 1, "\1")', states)
states = states.replace('A_JumpIfInventory("RSQ_MinigunAmmo",1,', 'A_JumpIfInventory("MinigunAmmoOff",1,')
assert 'FBF_USEAMMO' not in states and 'JumpIfNoAmmo' not in states and 'RSR_' not in states and 'RSQ_Empty' not in states
reload = '''	Reload:		// gen_off_minigun.py: the magazine tops up from the pouch (zscript/rsq/counters.zs OffFill)
		"####" "#" 0 A_JumpIfInventory("MinigunAmmoOff", 0, "Ready")	// full
		"####" "#" 0 A_JumpIfInventory("RSQ_MinigunAmmo", 1, "RSQ_OffFill")
		Goto Ready	// nothing in the pouch
	RSQ_OffFill:
		"####" "#" 0 A_PlaySound("Chaingun/beltQuiet", 5)
		"####" "#" 8 A_WeaponReady(WRF_NOFIRE | WRF_NOBOB)
		"####" "#" 0 A_GiveInventory("RSQ_OffFillMinigun", 1)
		"####" "#" 0 A_PlaySound("Chaingun/belt", 5)
		"####" "#" 8 A_WeaponReady(WRF_NOFIRE | WRF_NOBOB)
		Goto Ready
'''
states = states.replace('\tStates\n\t{\n', '\tStates\n\t{\n' + reload, 1)
hdr = '''// 2.0.5e GENERATED by tools/dual_minigun/gen_off_minigun.py from actors/Weapons/Minigun.dec. Do not edit by hand.
// The off-hand copy of BD22's Minigun (owner 2026-11-22: "The BD chaingun can be dual-wielded"), made as every copy in
// DECORATE.rsqdual is: the gun, renamed, its own magazine, the off hand only. Its own spin-up (RSQ_SpinOff), so each hand
// spins up on its own; the same shots, spread, damage and rate. See the script's header for every change.
ACTOR MinigunAmmoOff : Ammo
{
	Inventory.Amount 0
	Inventory.MaxAmount 200
	Ammo.BackpackAmount 0
	Ammo.BackpackMaxAmount 200
	+INVENTORY.IGNORESKILL
}

ACTOR RSQ_SpinOff : Inventory
{
	Inventory.MaxAmount 1
	+INVENTORY.UNDROPPABLE
	+INVENTORY.UNTOSSABLE
}

ACTOR RSQ_Off_Minigun : MiniGun
{
	Tag "Off-hand Minigun"
	Weapon.AmmoGive1 0
	Weapon.AmmoGive2 0
	Weapon.SelectionOrder 99999
	+WEAPON.OFFHANDWEAPON
	-WEAPON.NOHANDSWITCH	// it passes between hands; in the main hand it becomes its gun (dual.zs Hands)
	+WEAPON.CHEATNOTWEAPON

	Weapon.AmmoType1 "RSQ_MinigunAmmo"
	Weapon.AmmoType2 "MinigunAmmoOff"
	Weapon.AmmoUse2 0
	-INVENTORY.UNDROPPABLE
	Inventory.PickupSound "CBOXPKUP"
	Inventory.PickupMessage "$BDGOTCHAINGUN"
	Obituary "$OBBD_CHAINGUN"
'''
open(os.path.join(SRC, 'DECORATE.rsqdualmg'), 'w', encoding='latin-1').write(hdr + states.rstrip() + '\n')

# the model blocks
blocks = []
for f in ('MODELDEF.bd.txt', 'MODELDEF.rsqdual'):
    txt = rd(f)
    for m in re.finditer(r'(?m)^Model Minigun\s*\n\{.*?\n\}', txt, flags=re.S):
        blocks.append('// from %s\n' % f + re.sub(r'^Model Minigun', 'Model RSQ_Off_Minigun', m.group(0)))
assert len(blocks) == 7, len(blocks)
md = '// 2.0.5e GENERATED by tools/dual_minigun/gen_off_minigun.py: the off-hand Minigun uses its gun\'s own model blocks.\n\n' + '\n\n'.join(blocks) + '\n'
open(os.path.join(SRC, 'MODELDEF.rsqdualmg'), 'w', encoding='latin-1').write(md)
print('DECORATE.rsqdualmg: %d spin tokens renamed; MODELDEF.rsqdualmg: %d blocks' % (n_spin, len(blocks)))
